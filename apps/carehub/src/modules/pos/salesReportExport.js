// Excel and print/PDF builders for the Sales & Accounts report. Pure builders
// over the rows and summary that salesReport.js produced — nothing here
// recomputes a figure, so the file, the printout and the screen always agree.
// No cost or profit data is ever written.
//
// PDF follows the repo's established pattern (docs/architecture/ADR-Exports.md):
// a print-ready HTML document; the browser's "Save as PDF" makes the file.

import { neutraliseFormula, downloadBlob, printAsPdf } from '../business-directory/services/exportService'

const XLSX_MIME = 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
const MONEY_FMT = '#,##0.00'

export const SALES_REPORT_COLUMNS = [
  { key: 'date', header: 'Date', width: 18, numFmt: 'yyyy-mm-dd hh:mm' },
  { key: 'receipt', header: 'Receipt', width: 20 },
  { key: 'customer', header: 'Customer', width: 22 },
  { key: 'products', header: 'Products', width: 40 },
  { key: 'quantity', header: 'Qty', width: 7 },
  { key: 'total', header: 'Total (NGN)', width: 15, numFmt: MONEY_FMT },
  { key: 'discount', header: 'Discount (NGN)', width: 14, numFmt: MONEY_FMT },
  { key: 'paid', header: 'Paid (NGN)', width: 15, numFmt: MONEY_FMT },
  { key: 'outstanding', header: 'Outstanding (NGN)', width: 17, numFmt: MONEY_FMT },
  { key: 'refunded', header: 'Refunded (NGN)', width: 15, numFmt: MONEY_FMT },
  { key: 'method', header: 'Payment method', width: 22 },
  { key: 'status', header: 'Payment status', width: 14 },
  { key: 'cashier', header: 'Cashier', width: 18 },
  { key: 'shift', header: 'Shift', width: 24 },
]

// One list of summary lines for both formats, in reading order.
export function summaryLines(summary) {
  const lines = [
    ['Total sales', summary.totalSales],
    ['Transactions', summary.transactions, 'count'],
    ['Discounts given', summary.discounts],
    ['Payments received', summary.received.total],
    ['  Cash', summary.received.Cash],
    ['  Transfer', summary.received.Transfer],
    ['  POS', summary.received.POS],
  ]
  if (summary.received.Unspecified) lines.push(['  Method not recorded', summary.received.Unspecified])
  lines.push(
    ['  of which credit repayments', summary.collections],
    ['Refunds', summary.refunds.total],
    ['Net received', summary.netReceived],
    ['Cash in hand (cash received less cash refunds)', summary.cashInHand],
    ['Credit given', summary.credit.amount],
    ['Credit sales', summary.credit.count, 'count'],
    ['Outstanding balance', summary.outstanding],
  )
  return lines
}

const timeText = (d) => (d instanceof Date && !Number.isNaN(d.getTime()) ? d.toLocaleString('en-NG') : '')

export async function buildSalesReportXlsx({ rows, summary, meta }) {
  const ExcelJS = (await import('exceljs')).default
  const wb = new ExcelJS.Workbook()
  wb.creator = 'CareHub'
  wb.created = new Date()

  const ws = wb.addWorksheet('Summary')
  ws.columns = [{ width: 46 }, { width: 22 }]
  const text = (v) => neutraliseFormula(String(v ?? ''))
  ws.addRow(['Sales & Accounts Report']).font = { bold: true, size: 14 }
  ws.addRow(['Business', text(meta.businessName)])
  ws.addRow(['Period', text(meta.periodLabel)])
  ws.addRow(['Filters', text(meta.filtersLabel || 'None')])
  ws.addRow(['Generated by', text(meta.generatedBy)])
  ws.addRow(['Generated at', timeText(meta.generatedAt)])
  if (summary.estimated) ws.addRow(['Note', 'Money figures are estimated: the payments ledger is not available yet.'])
  ws.addRow([])
  for (const [label, value, kind] of summaryLines(summary)) {
    const r = ws.addRow([label, value])
    if (kind !== 'count') r.getCell(2).numFmt = MONEY_FMT
    if (!label.startsWith('  ')) r.getCell(1).font = { bold: true }
  }

  const tx = wb.addWorksheet('Transactions', { views: [{ state: 'frozen', ySplit: 1 }] })
  tx.columns = SALES_REPORT_COLUMNS.map((c) => ({ header: c.header, key: c.key, width: c.width, style: c.numFmt ? { numFmt: c.numFmt } : {} }))
  tx.getRow(1).font = { bold: true }
  tx.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: SALES_REPORT_COLUMNS.length } }
  for (const r of rows) {
    tx.addRow(Object.fromEntries(SALES_REPORT_COLUMNS.map((c) => [c.key, typeof r[c.key] === 'string' ? neutraliseFormula(r[c.key]) : r[c.key]])))
  }

  const buf = await wb.xlsx.writeBuffer()
  return new Blob([buf], { type: XLSX_MIME })
}

const esc = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;')
const naira = (n) => '₦' + Number(n || 0).toLocaleString('en-NG', { minimumFractionDigits: 0, maximumFractionDigits: 2 })

export function buildSalesReportHtml({ rows, summary, meta }) {
  const lines = summaryLines(summary).map(([label, value, kind]) =>
    `<tr class="${label.startsWith('  ') ? 'sub' : ''}"><td>${esc(label.trim())}</td><td class="n">${kind === 'count' ? esc(value) : esc(naira(value))}</td></tr>`).join('')
  const body = rows.length
    ? rows.map((r) => `<tr>
        <td>${esc(timeText(r.date))}</td><td>${esc(r.receipt)}</td><td>${esc(r.customer)}</td><td>${esc(r.products)}</td>
        <td class="n">${esc(r.quantity)}</td><td class="n">${esc(naira(r.total))}</td><td class="n">${esc(naira(r.paid))}</td>
        <td class="n">${esc(naira(r.outstanding))}</td><td class="n">${r.refunded ? esc(naira(r.refunded)) : ''}</td>
        <td>${esc(r.method)}</td><td>${esc(r.status)}</td><td>${esc(r.cashier)}</td></tr>`).join('')
    : '<tr><td colspan="12" class="empty">No sales match this period and these filters.</td></tr>'
  return `<!doctype html><html><head><meta charset="utf-8"><title>Sales report · ${esc(meta.businessName)} · ${esc(meta.periodLabel)}</title>
<style>
  body{font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif;color:#0f172a;margin:24px;font-size:12px}
  h1{font-size:18px;margin:0 0 4px} .meta{color:#475569;margin:0 0 16px;line-height:1.6}
  .note{background:#fef3c7;color:#92400e;padding:8px 10px;border-radius:6px;margin-bottom:12px}
  table{border-collapse:collapse;width:100%} th,td{border:1px solid #e2e8f0;padding:6px 8px;text-align:left;vertical-align:top}
  th{background:#f1f5f9} .n{text-align:right;white-space:nowrap} .sub td:first-child{padding-left:22px;color:#475569}
  .summary{width:auto;min-width:360px;margin-bottom:20px} .empty{text-align:center;color:#94a3b8;padding:20px}
  @media print{body{margin:10mm} tr{page-break-inside:avoid}}
</style></head><body>
<h1>Sales &amp; Accounts Report</h1>
<p class="meta">${esc(meta.businessName)} · ${esc(meta.periodLabel)}<br>Filters: ${esc(meta.filtersLabel || 'None')}<br>
Generated by ${esc(meta.generatedBy)} on ${esc(timeText(meta.generatedAt))}</p>
${summary.estimated ? '<p class="note">Money figures are estimated: the payments ledger is not available yet.</p>' : ''}
<table class="summary"><tbody>${lines}</tbody></table>
<table><thead><tr><th>Date</th><th>Receipt</th><th>Customer</th><th>Products</th><th class="n">Qty</th><th class="n">Total</th>
<th class="n">Paid</th><th class="n">Outstanding</th><th class="n">Refunded</th><th>Method</th><th>Status</th><th>Cashier</th></tr></thead>
<tbody>${body}</tbody></table></body></html>`
}

const stamp = () => new Date().toISOString().slice(0, 10)

// Builds the file, gives the caller one chance to veto (the export audit
// record is written there), then saves it. Same contract as the inventory export.
export async function exportSalesReportXlsx(input, { beforeDownload } = {}) {
  const blob = await buildSalesReportXlsx(input)
  if (beforeDownload && (await beforeDownload()) === false) return false
  downloadBlob(blob, `CareHub_Sales_Report_${stamp()}.xlsx`)
  return true
}

export function printSalesReport(input) {
  printAsPdf(buildSalesReportHtml(input))
}
